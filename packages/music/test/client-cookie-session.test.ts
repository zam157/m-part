import { afterEach, expect, it, vi } from 'vitest'
vi.mock('../src/utils/constants', () => ({ TARGET_EXTENSION: true }))
import { getQQSession, qqToken } from '../src/utils/providers/qq-session'
import { getNeteaseCsrfToken } from '../src/utils/providers/netease-session'
import { CLIENT_COOKIE_PREFIX, CLIENT_COOKIE_MODE_PREFIX, getClientSessionCookie, watchWebsiteSessionCookies } from '../src/utils/client-cookies'
afterEach(() => { localStorage.clear(); vi.unstubAllGlobals() })

it('derives QQ account and token exclusively from the manual cookie, without mixing browser fields', async () => {
  const get = vi.fn(async () => ({ value: 'browser-account' }))
  vi.stubGlobal('chrome', { cookies: { get } })
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'qq', 'qqmusic_uin=456; qqmusic_key=manual-key')
  expect(await getQQSession()).toEqual({ uin: '456', key: 'manual-key', token: qqToken('manual-key'), cookieContext: 'qqmusic_uin=456; qqmusic_key=manual-key' })
  expect(get).not.toHaveBeenCalled()
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'qq', 'qqmusic_key=manual-key')
  expect((await getQQSession()).uin).toBe('0')
  expect(get).not.toHaveBeenCalled()
})
it('uses the manual Netease CSRF token, including an explicitly missing token, then restores browser lookup', async () => {
  const get = vi.fn(async () => ({ value: 'browser-csrf' }))
  vi.stubGlobal('chrome', { cookies: { get } })
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'netease', 'MUSIC_U=manual; __csrf=manual-csrf')
  expect(await getNeteaseCsrfToken()).toBe('manual-csrf')
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'netease', 'MUSIC_U=manual')
  expect(await getNeteaseCsrfToken()).toBe('')
  expect(get).not.toHaveBeenCalled()
  localStorage.removeItem(CLIENT_COOKIE_PREFIX + 'netease')
  expect(await getNeteaseCsrfToken()).toBe('browser-csrf')
})
it('uses website authentication fields while retaining saved manual QQ and Netease Cookies', async () => {
  const values: Record<string, string> = { qqmusic_uin: '123', qqmusic_key: 'website-key', __csrf: 'website-csrf' }
  vi.stubGlobal('chrome', { cookies: { get: async ({ name }: { name: string }) => ({ value: values[name] ?? '' }) } })
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'qq', 'qqmusic_uin=456; qqmusic_key=manual-key')
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'netease', 'MUSIC_U=manual; __csrf=manual-csrf')
  for (const source of ['qq', 'netease']) localStorage.setItem(CLIENT_COOKIE_MODE_PREFIX + source, 'website')
  expect(await getQQSession()).toMatchObject({ uin: '123', key: 'website-key', token: qqToken('website-key'), cookieContext: '' })
  expect(await getNeteaseCsrfToken()).toBe('website-csrf')
  for (const source of ['qq', 'netease']) localStorage.setItem(CLIENT_COOKIE_MODE_PREFIX + source, 'manual')
  expect((await getQQSession()).uin).toBe('456')
  expect(await getNeteaseCsrfToken()).toBe('manual-csrf')
})
it('exports only the active manual session login fields without reading browser Cookies', async () => {
  const getAll = vi.fn()
  vi.stubGlobal('chrome', { cookies: { getAll } })
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'netease', 'MUSIC_U=manual; __csrf=token; unrelated=private')
  expect(await getClientSessionCookie('netease')).toBe('MUSIC_U=manual; __csrf=token')
  expect(getAll).not.toHaveBeenCalled()
})
it('exports website login fields in website mode, ignoring retained manual values and unrelated browser Cookies', async () => {
  vi.stubGlobal('chrome', { cookies: { getAll: vi.fn(async () => [{ name: 'MUSIC_U', value: 'website', path: '/' }, { name: 'other', value: 'private', path: '/' }]) } })
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'netease', 'MUSIC_U=inactive')
  localStorage.setItem(CLIENT_COOKIE_MODE_PREFIX + 'netease', 'website')
  expect(await getClientSessionCookie('netease')).toBe('MUSIC_U=website')
  localStorage.setItem(CLIENT_COOKIE_MODE_PREFIX + 'bili', 'website')
  expect(await getClientSessionCookie('bili')).toBe('')
})
it('does not replace missing manual login fields with website credentials', async () => {
  const getAll = vi.fn()
  vi.stubGlobal('chrome', { cookies: { getAll } })
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'qq', 'uin=123; unrelated=value')
  await expect(getClientSessionCookie('qq')).rejects.toThrow('缺少登录字段')
  expect(getAll).not.toHaveBeenCalled()
})
it('reads login Cookies scoped to API paths rather than only the website root', async () => {
  const getAll = vi.fn(async ({ url }: { url: string }) => new URL(url).pathname.startsWith('/weapi/') ? [{ name: 'MUSIC_U', value: 'api-session', path: '/weapi/' }] : [])
  vi.stubGlobal('chrome', { cookies: { getAll } })
  expect(await getClientSessionCookie('netease')).toBe('MUSIC_U=api-session')
  expect(getAll).toHaveBeenCalledExactlyOnceWith({ url: 'https://music.163.com/weapi/w/nuser/account/get' })
})
it('uses a complete website session when the API host has no login Cookies', async () => {
  vi.stubGlobal('chrome', { cookies: { getAll: vi.fn(async ({ url }: { url: string }) => url === 'https://www.bilibili.com/' ? [{ name: 'SESSDATA', value: 'website-session', path: '/' }] : []) } })
  expect(await getClientSessionCookie('bili')).toBe('SESSDATA=website-session')
})
it('does not mix incomplete accounts from different website and API Cookie scopes', async () => {
  vi.stubGlobal('chrome', { cookies: { getAll: vi.fn(async ({ url }: { url: string }) => url === 'https://y.qq.com/' ? [{ name: 'uin', value: '111', path: '/' }] : [{ name: 'qqmusic_key', value: 'different-account-key', path: '/' }]) } })
  await expect(getClientSessionCookie('qq')).rejects.toThrow('网站登录 Cookie 不完整')
})
it('reports missing website host permissions instead of silently exporting an anonymous session', async () => {
  const getAll = vi.fn(async () => [])
  vi.stubGlobal('chrome', { cookies: { getAll }, permissions: { contains: vi.fn(async () => false) } })
  await expect(getClientSessionCookie('bili')).rejects.toThrow('允许访问音源网站')
  expect(getAll).not.toHaveBeenCalled()
})
it.each(['bili', 'qq'] as const)('reports a missing parent Cookie domain permission even when query hosts are allowed: %s', async (provider) => {
  const parent = provider === 'bili' ? 'bilibili.com' : 'qq.com'
  const contains = vi.fn(async ({ origins }: { origins: string[] }) => origins.every(origin => new URL(origin.replace('*://', 'https://')).hostname !== parent))
  // Chrome filters out parent-domain Cookies without throwing, even for an allowed query URL.
  const getAll = vi.fn(async () => [])
  vi.stubGlobal('chrome', { cookies: { getAll }, permissions: { contains } })
  await expect(getClientSessionCookie(provider)).rejects.toThrow('允许访问音源网站')
  expect(getAll).not.toHaveBeenCalled()
})
it('requires HTTP Cookie-domain permission too, because non-Secure Cookies are checked against HTTP', async () => {
  const getAll = vi.fn(async () => [])
  const contains = vi.fn(async ({ origins }: { origins: string[] }) => origins.every(origin => origin.startsWith('https://')))
  vi.stubGlobal('chrome', { cookies: { getAll }, permissions: { contains } })
  await expect(getClientSessionCookie('netease')).rejects.toThrow('允许访问音源网站')
  expect(getAll).not.toHaveBeenCalled()
})
it('reports Cookie API failures without exposing the original error or treating them as logout', async () => {
  vi.stubGlobal('chrome', { cookies: { getAll: vi.fn(async () => { throw new Error('SESSDATA=private-error') }) } })
  await expect(getClientSessionCookie('bili')).rejects.toThrow('无法完整读取网站登录 Cookie')
  vi.stubGlobal('chrome', {})
  await expect(getClientSessionCookie('bili')).rejects.toThrow('重新加载扩展并检查权限')
})
it('exports no login credential only when all permitted scopes genuinely have no login fields', async () => {
  vi.stubGlobal('chrome', { cookies: { getAll: vi.fn(async () => [{ name: 'buvid3', value: 'anonymous-visitor', path: '/' }]) }, permissions: { contains: vi.fn(async () => true) } })
  expect(await getClientSessionCookie('bili')).toBe('')
})
it('does not treat a QQ visitor UIN without a login key as a broken signed-in account', async () => {
  vi.stubGlobal('chrome', { cookies: { getAll: vi.fn(async () => [{ name: 'uin', value: '0', path: '/' }]) } })
  expect(await getClientSessionCookie('qq')).toBe('')
})
it('observes only declared session fields in the selected website mode and removes the listener', () => {
  vi.useFakeTimers()
  let listener!: (event: { cookie: { domain: string, name: string } }) => void
  const remove = vi.fn()
  vi.stubGlobal('chrome', { cookies: { onChanged: { addListener: (value: typeof listener) => { listener = value }, removeListener: remove } } })
  const changed = vi.fn()
  const stop = watchWebsiteSessionCookies(changed)
  listener({ cookie: { domain: '.music.163.com', name: 'MUSIC_U' } })
  listener({ cookie: { domain: '.evil.music.163.com', name: 'MUSIC_U' } })
  listener({ cookie: { domain: '.music.163.com', name: 'unrelated' } })
  vi.advanceTimersByTime(100)
  localStorage.setItem(CLIENT_COOKIE_PREFIX + 'netease', 'MUSIC_U=manual')
  listener({ cookie: { domain: '.music.163.com', name: 'MUSIC_U' } })
  expect(changed).toHaveBeenCalledExactlyOnceWith('netease')
  listener({ cookie: { domain: 'api.bilibili.com', name: 'SESSDATA' } })
  vi.advanceTimersByTime(100)
  expect(changed).toHaveBeenLastCalledWith('bili')
  expect(changed).toHaveBeenCalledTimes(2)
  stop(); expect(remove).toHaveBeenCalledWith(listener)
  vi.useRealTimers()
})
